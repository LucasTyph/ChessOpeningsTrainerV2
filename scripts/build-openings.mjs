// Regenerates src/openings-data.js from the lichess chess-openings list (CC0):
// https://github.com/lichess-org/chess-openings
// Run: node scripts/build-openings.mjs   (needs internet; the result is committed)

import { writeFileSync } from 'node:fs';
import { Chess } from 'chess.js';
import { fenKey, hashKey } from '../src/openings.js';

const BASE = 'https://raw.githubusercontent.com/lichess-org/chess-openings/master/';
const positions = new Map(); // hash -> { name, moves: Map(san -> count) }
const at = (fen) => {
  const h = hashKey(fenKey(fen));
  if (!positions.has(h)) positions.set(h, { name: '', moves: new Map() });
  return positions.get(h);
};

let lines = 0;
for (const file of ['a', 'b', 'c', 'd', 'e']) {
  const res = await fetch(`${BASE}${file}.tsv`);
  if (!res.ok) throw new Error(`${file}.tsv: HTTP ${res.status}`);
  const rows = (await res.text()).split('\n').slice(1).filter(Boolean);
  for (const row of rows) {
    const [eco, name, pgn] = row.split('\t');
    const sans = pgn.trim().split(/\s+/).filter((t) => !t.endsWith('.'));
    const chess = new Chess();
    for (const san of sans) {
      const pos = at(chess.fen());
      const mv = chess.move(san);
      pos.moves.set(mv.san, (pos.moves.get(mv.san) || 0) + 1);
    }
    const end = at(chess.fen());
    if (!end.name) end.name = `${eco} ${name.replace(/\|/g, '/')}`;
    lines++;
  }
}

const out = [];
for (const [hash, p] of positions) {
  const moves = [...p.moves].sort((a, b) => b[1] - a[1]).map(([san, n]) => (n > 1 ? `${san}:${n}` : san)).join(',');
  out.push(`${hash}|${p.name}|${moves}`);
}
writeFileSync(new URL('../src/openings-data.js', import.meta.url),
  `// Generated by scripts/build-openings.mjs from lichess-org/chess-openings (CC0). Do not edit.\nexport const BOOK = ${JSON.stringify(out.join('\n'))};\n`);
console.log(`${lines} named lines, ${positions.size} positions`);
